    /**
     * Chuẩn hóa văn bản tìm kiếm, hỗ trợ tiếng Việt có dấu và không dấu.
     * Locale.ROOT tránh để ngôn ngữ hệ thống làm thay đổi cách so khớp tên kỹ thuật.
     */
    private fun normalizeSearchText(text: String): String =
        Normalizer.normalize(text.lowercase(Locale.ROOT), Normalizer.Form.NFD)
            .replace("\\p{M}+".toRegex(), "")
            .replace('đ', 'd')

    /**
     * Điểm khớp: tiêu đề chính xác 100, tiền tố 80, chứa 60; từ khóa 40;
     * mô tả 25; đường dẫn phân cấp 20; tên nhóm 10; khớp đủ các từ 50.
     */
    fun search(query: String): List<SettingsSearchItem> {
        val trimmed = normalizeSearchText(query.trim())
        if (trimmed.isEmpty()) return allItems
        val subQueries = trimmed.split("\\s+".toRegex()).filter { it.isNotEmpty() }

        return allItems
            .mapNotNull { item ->
                var score = 0
                val titleLower = normalizeSearchText(item.title)
                val subtitleLower = normalizeSearchText(item.subtitle)
                val categoryLower = normalizeSearchText(item.category.label)
                val breadcrumbLower = normalizeSearchText(item.breadcrumb.orEmpty())
                val keywordsLower = item.keywords.map(::normalizeSearchText)

                if (titleLower == trimmed) {
                    score += 100
                } else if (titleLower.startsWith(trimmed)) {
                    score += 80
                } else if (titleLower.contains(trimmed)) {
                    score += 60
                }
                if (keywordsLower.any { it.contains(trimmed) }) score += 40
                if (subtitleLower.contains(trimmed)) score += 25
                if (breadcrumbLower.contains(trimmed)) score += 20
                if (categoryLower.contains(trimmed)) score += 10

                if (subQueries.size > 1) {
                    val allMatched = subQueries.all { sub ->
                        titleLower.contains(sub) || subtitleLower.contains(sub) ||
                            breadcrumbLower.contains(sub) || keywordsLower.any { it.contains(sub) }
                    }
                    if (allMatched) score += 50
                }
                if (score > 0) item to score else null
            }
            .sortedByDescending { it.second }
            .map { it.first }
    }
